/**
 * Cron Scheduler Mini-Service — Phase 4.6
 *
 * Spec: docs/FULLSTACK_CAPABILITY_PLAN_V2.md Phase 4.6 (lines 263-281)
 *
 * A standalone Bun HTTP server on port 3004 that:
 *   1. Exposes REST endpoints to manage cron jobs (CRUD).
 *   2. Runs a background tick loop (every 30s by default) that queries the DB
 *      for jobs whose nextRunAt <= now AND status='active', then executes them
 *      in parallel via /api/openclaw/sessions?action=run (routed through Caddy
 *      via XTransformPort=3000 query parameter).
 *
 * Architecture notes:
 *   - This service reads the same SQLite DB as the main Next.js app
 *     (DATABASE_URL env var). It uses the Prisma client generated by the
 *     parent project (../../node_modules/.prisma) — we don't bundle a separate
 *     client.
 *   - All HTTP requests to the main app use relative paths with
 *     XTransformPort=3000 query parameter so Caddy routes them to the correct
 *     port. NEVER use absolute localhost URLs.
 *   - The service auto-spawns via instrumentation-node.ts (Phase 4.6 wiring).
 *
 * Health check:
 *   GET /health → 200 { ok: true, port: 3004, due: <count>, lastTick: <iso> }
 */

import { createServer } from 'http'
import { execSync } from 'child_process'

const PORT = 3004
const TICK_INTERVAL_MS = 30_000

/** Root-cause fix (2026-08-25 post-deploy audit): an orphaned previous
 *  instance of this service (from a killed app process) can still hold port
 *  3004 — the new instance then dies with "Failed to start server. Is port
 *  3004 in use?" and the service-manager gives up after 3 retries. Kill any
 *  orphaned port holders before binding. */
function killPortHolders(port: number): void {
  try {
    const out = execSync(`lsof -ti :${port} 2>/dev/null || true`, { encoding: 'utf-8', timeout: 3000 })
    const pids = out.split('\n').map(s => s.trim()).filter(s => /^\d+$/.test(s))
    for (const pidStr of pids) {
      const pid = parseInt(pidStr, 10)
      if (pid === process.pid) continue // never kill ourselves
      try {
        console.log(`[cron-scheduler] Killing orphaned port ${port} holder PID ${pid}...`)
        process.kill(pid, 'SIGKILL')
      } catch { /* already dead */ }
    }
    if (pids.length > 0) {
      const start = Date.now()
      while (Date.now() - start < 1000) { /* brief settle for socket release */ }
    }
  } catch { /* lsof unavailable — non-fatal */ }
}

killPortHolders(PORT)

// Read the same DATABASE_URL as the parent app (set in .env / instrumentation).
const DATABASE_URL = process.env.DATABASE_URL
if (!DATABASE_URL) {
  console.error('[cron-scheduler] FATAL: DATABASE_URL is not set — cannot connect to DB')
  process.exit(1)
}

// ============================================================
// Lazy load the scheduler (re-uses the parent project's Prisma client).
// The parent project's tsconfig sets up path aliases; for standalone Bun
// execution we use relative imports + bun's auto TypeScript support.
// ============================================================
let schedulerModule: typeof import('../../src/lib/cron/scheduler') | null = null
async function getScheduler() {
  if (schedulerModule) return schedulerModule
  try {
    // Bun resolves this relative to the cwd at runtime (instrumentation-node
    // starts the service with cwd = parent project root).
    schedulerModule = await import('../../src/lib/cron/scheduler')
    return schedulerModule
  } catch (err) {
    console.error('[cron-scheduler] Could not load scheduler module:', err)
    return null
  }
}

// ============================================================
// Tick loop state
// ============================================================
let lastTick: Date | null = null
let lastDueCount = 0
let isTickRunning = false

async function tickLoop(): Promise<void> {
  if (isTickRunning) return
  isTickRunning = true
  try {
    const sched = await getScheduler()
    if (sched) {
      lastDueCount = await sched.tickCronScheduler()
    }
    lastTick = new Date()
  } catch (err) {
    console.error('[cron-scheduler] tick error:', err)
  } finally {
    isTickRunning = false
  }
}

// Start the tick loop (every 30s). setInterval (not setTimeout chain) for simplicity.
setInterval(() => {
  tickLoop().catch(err => console.error('[cron-scheduler] tick crashed:', err))
}, TICK_INTERVAL_MS)

// Run one tick immediately on startup so any past-due jobs fire right away
setTimeout(() => {
  tickLoop().catch(err => console.error('[cron-scheduler] initial tick crashed:', err))
}, 1000)

// ============================================================
// HTTP server — exposes CRUD endpoints + health check
// ============================================================
const server = createServer(async (req, res) => {
  const url = new URL(req.url || '', `http://localhost:${PORT}`)
  const path = url.pathname
  const method = req.method || 'GET'

  // Helper for JSON responses
  const json = (status: number, body: unknown) => {
    res.writeHead(status, { 'Content-Type': 'application/json' })
    res.end(JSON.stringify(body))
  }

  // Read request body (for POST)
  const readBody = (): Promise<string> => new Promise((resolve) => {
    let data = ''
    req.on('data', (chunk) => { data += chunk })
    req.on('end', () => resolve(data))
  })

  try {
    // GET /health — basic liveness probe
    if (method === 'GET' && path === '/health') {
      return json(200, {
        ok: true,
        service: 'cron-scheduler',
        port: PORT,
        tickIntervalMs: TICK_INTERVAL_MS,
        lastTick: lastTick ? lastTick.toISOString() : null,
        lastDueCount,
        isTickRunning,
      })
    }

    const sched = await getScheduler()
    if (!sched) {
      return json(500, { ok: false, error: 'Scheduler module not loaded' })
    }

    // GET /jobs — list jobs (optional ?status=active)
    if (method === 'GET' && path === '/jobs') {
      const status = url.searchParams.get('status') as
        | 'active' | 'paused' | 'completed' | 'failed' | null
      const sessionId = url.searchParams.get('sessionId') || undefined
      const jobs = await sched.listCronJobs({ status: status || undefined, sessionId })
      return json(200, { ok: true, jobs, count: jobs.length })
    }

    // POST /jobs — create a new cron job
    if (method === 'POST' && path === '/jobs') {
      const bodyText = await readBody()
      const body = bodyText ? JSON.parse(bodyText) : {}
      const { schedule, task, sessionId, agentId } = body
      if (!schedule || !schedule.kind || !schedule.expr || !task) {
        return json(400, { ok: false, error: 'create requires { schedule: { kind, expr }, task }' })
      }
      const created = await sched.createCronJob({
        schedule,
        task: String(task),
        sessionId: sessionId ? String(sessionId) : undefined,
        agentId: agentId ? String(agentId) : undefined,
      })
      return json(200, {
        ok: true,
        jobId: created.jobId,
        nextRun: created.nextRun?.toISOString() ?? null,
        dryRun: created.dryRun,
        jobHash: created.jobHash,
        duplicate: created.duplicate,
      })
    }

    // DELETE /jobs/:id — soft-delete a job (sets status='paused')
    if (method === 'DELETE' && path.startsWith('/jobs/')) {
      const jobId = path.replace('/jobs/', '')
      if (!jobId) return json(400, { ok: false, error: 'jobId is required' })
      const result = await sched.deleteCronJob(jobId)
      return json(result.success ? 200 : 404, { ok: result.success, jobId, error: result.error })
    }

    // POST /jobs/:id/run — manually trigger a job (for testing)
    if (method === 'POST' && path.startsWith('/jobs/') && path.endsWith('/run')) {
      const jobId = path.replace('/jobs/', '').replace('/run', '')
      if (!jobId) return json(400, { ok: false, error: 'jobId is required' })
      const result = await sched.runCronJob(jobId)
      return json(result.success ? 200 : 500, {
        ok: result.success,
        jobId,
        result: result.result,
        error: result.error,
      })
    }

    // POST /tick — manual tick trigger (for testing)
    if (method === 'POST' && path === '/tick') {
      const executed = await sched.tickCronScheduler()
      return json(200, { ok: true, executed })
    }

    return json(404, { ok: false, error: `Not found: ${method} ${path}` })
  } catch (err) {
    return json(500, {
      ok: false,
      error: err instanceof Error ? err.message : 'Unknown error',
    })
  }
})

server.listen(PORT, () => {
  console.log(`[cron-scheduler] listening on http://localhost:${PORT} (tick interval: ${TICK_INTERVAL_MS}ms)`)
})

// Graceful shutdown
function shutdown(signal: string) {
  console.log(`[cron-scheduler] received ${signal} — shutting down`)
  server.close(() => {
    console.log('[cron-scheduler] server closed')
    process.exit(0)
  })
  // Force exit after 5s if close hangs
  setTimeout(() => process.exit(1), 5000).unref()
}
process.on('SIGTERM', () => shutdown('SIGTERM'))
process.on('SIGINT', () => shutdown('SIGINT'))
