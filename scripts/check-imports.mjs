#!/usr/bin/env bun
/**
 * TMO CHECK-IMPORTS (Task 42 — cross-import gate)
 * =================================================
 *
 * Trước Task 42, "cross-import" chỉ là KỶ LUẬT THỦ CÔNG (~35 chỗ comment
 * "avoid circular dependency" rải rác) — KHÔNG có gì enforce tự động: eslint
 * không có no-restricted-imports, quality-gate không check, CI không check.
 * Script này bổ sung 2 lớp kiểm tra tự động:
 *
 *   1. IMPORT BOUNDARY — ranh giới kiến trúc bắt buộc:
 *        a. src/** KHÔNG được import từ mini-services/** (app và mini-services
 *           giao tiếp qua HTTP, không qua code — ranh giới process).
 *        b. mini-services/** KHÔNG được import từ src/** (@/... hoặc ../src).
 *
 *   2. CIRCULAR IMPORT — phát hiện chu trình import tĩnh (A→B→A):
 *      Codebase quản lý vòng bằng dynamic import() + comment thủ công; script
 *      phát hiện các chu trình TĨNH (import/require thường) còn sót. Danh sách
 *      chu trình CŨ đã biết (baseline — có chủ đích, đang được xử lý bằng
 *      dynamic import ở call-site khác) chỉ WARN; chu trình MỚI → FAIL.
 *
 * Không parse đầy đủ AST (không cần dependency ngoài) — regex import đủ chính
 * xác cho codebase này: mọi specifer trong chuỗi '...' hoặc "...".
 *
 * Usage:
 *   bun scripts/check-imports.mjs           (quality-gate stage `imports`)
 *   bun scripts/check-imports.mjs --verbose (in cả baseline cycles)
 *
 * Exit code: 0 = PASS (boundary sạch, không có circular MỚI) · 1 = FAIL.
 */

import * as fs from 'node:fs'
import * as path from 'node:path'

const ROOT = path.resolve(import.meta.dir, '..')
const SRC_DIR = path.join(ROOT, 'src')
const MINI_DIR = path.join(ROOT, 'mini-services')

const verbose = process.argv.includes('--verbose')

// ---------------------------------------------------------------------------
// Chu trình import tĩnh đã biết (baseline) — mỗi entry là chuỗi tên module
// canonical (sorted, join ' -> '). Khi phát hiện cycle: so khớp với baseline
// → WARN thay vì FAIL. Thêm baseline MỚI = quyết định có chủ đích + comment.
// ---------------------------------------------------------------------------
const KNOWN_CYCLES = [
  // (chạy lần đầu Task 42: 0 chu trình tĩnh — baseline rỗng)
]

const SCAN_DIRS = []
if (fs.existsSync(SRC_DIR)) SCAN_DIRS.push(SRC_DIR)
if (fs.existsSync(MINI_DIR)) SCAN_DIRS.push(MINI_DIR)

// ---------------------------------------------------------------------------
// Boundary exceptions CÓ CHỦ ĐÍCH (mỗi entry = 1 cạnh import được phép):
// • cron-scheduler → src/lib/cron/scheduler: thiết kế Phase 4.6 — mini-service
//   đọc CÙNG SQLite DB + Prisma client của parent (comment đầu file index.ts:
//   "uses the Prisma client generated by the parent project"), tái dùng logic
//   parse cron/dedup/retry 564 dòng thay vì duplicate. Mọi cạnh src↔mini KHÁC
//   đều là vi phạm kiến trúc (app giao tiếp mini-services qua HTTP).
// • gateway-bridge → src/lib/protected-paths: ROUND-6 (2026-10-28, user
//   directive "chặn như lớp 1") — bridge (18791, KHÔNG auth, đích cuối của mọi
//   tool exec/write/edit/apply_patch) phải chạy CÙNG guard protected-path với
//   app. Guard ~640 dòng; duplicate tạo 2 nguồn chân lý → lệch danh sách
//   protected giữa app và bridge = LỖ HỔNG bảo mật âm thầm. Import trực tiếp
//   giữ đồng bộ 100% (protected-paths.ts chỉ import 'path' — không kéo thêm
//   dependency nào của app).
// ---------------------------------------------------------------------------
const BOUNDARY_ALLOWLIST = new Set([
  'mini-services/cron-scheduler/index.ts -> src/lib/cron/scheduler.ts',
  'mini-services/gateway-bridge/index.ts -> src/lib/protected-paths.ts',
])

const SKIP_DIRS = new Set([
  'node_modules', '.next', '.next-qa', 'out', 'build', 'dist',
  '.git', '.turbo', 'coverage', '__pycache__',
])
const EXTS = ['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs']

// ---------------------------------------------------------------------------
// Thu thập file + parse imports
// ---------------------------------------------------------------------------
const files = [] // absolute paths
function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue
      walk(path.join(dir, entry.name))
    } else if (EXTS.some((e) => entry.name.endsWith(e)) && !entry.name.endsWith('.d.ts')) {
      files.push(path.join(dir, entry.name))
    }
  }
}
for (const d of SCAN_DIRS) walk(d)

/** Chuẩn hóa module key: path tuyệt đối → path relative từ ROOT (POSIX sep) */
const toKey = (abs) => path.relative(ROOT, abs).split(path.sep).join('/')

/** Resolve specifier → absolute file (null nếu là external package/asset) */
function resolveSpec(fromFile, spec) {
  if (!spec) return null
  let base = null
  if (spec.startsWith('@/')) {
    base = path.join(SRC_DIR, spec.slice(2))
  } else if (spec.startsWith('./') || spec.startsWith('../')) {
    base = path.resolve(path.dirname(fromFile), spec)
  } else if (spec.startsWith('mini-services/') || spec.startsWith('../mini-services/')) {
    base = path.resolve(ROOT, spec)
  } else {
    return null // external package (next, react, prisma...) hoặc asset
  }
  // Extensionless resolve: thử từng đuôi rồi index.*
  const candidates = []
  for (const e of EXTS) candidates.push(base + e)
  for (const e of EXTS) candidates.push(path.join(base, 'index' + e))
  for (const c of candidates) {
    if (fs.existsSync(c) && fs.statSync(c).isFile()) return c
  }
  return null
}

// STATIC import — tạo edge cho CẢ boundary lẫn circular graph.
const STATIC_IMPORT_RE = [
  /import\s+[^'"\n]*?from\s*['"]([^'"]+)['"]/g, // import ... from 'x'
  /import\s*['"]([^'"]+)['"]/g,                 // import 'x' (side-effect)
  /require\(\s*['"]([^'"]+)['"]\s*\)/g,         // require('x')
]
// DYNAMIC import('x') — KHÔNG tạo edge circular: đây chính là pattern PHÁ VÒNG
// có chủ đích của codebase (~35 chỗ "avoid circular dependency"); nhưng VẪN
// bị check boundary (mini-services kéo code app qua dynamic vẫn là vi phạm).
const DYNAMIC_IMPORT_RE = /import\(\s*['"]([^'"]+)['"]\s*\)/g

// graph: key -> Set(key) — chỉ edge STATIC (circular check); edgeMeta cho debug
const graph = new Map()
const edgeMeta = new Map()
const boundaryViolations = [] // { from, spec, resolvedTo }

/** Xử lý 1 specifier đã resolve — boundary check + (staticOnly ? graph edge) */
function recordEdge(file, fromKey, spec, resolved, staticOnly) {
  const resolvedKey = toKey(resolved)
  if (resolvedKey === fromKey) return
  if (staticOnly) {
    graph.get(fromKey).add(resolvedKey)
    if (!edgeMeta.has(`${fromKey} -> ${resolvedKey}`)) {
      edgeMeta.set(`${fromKey} -> ${resolvedKey}`, { fromFile: file, spec })
    }
  }
  // ---- BOUNDARY RULES (áp cho static + dynamic) ----
  const inSrc = fromKey.startsWith('src/')
  const inMini = fromKey.startsWith('mini-services/')
  const targetSrc = resolvedKey.startsWith('src/')
  const targetMini = resolvedKey.startsWith('mini-services/')
  if ((inSrc && targetMini) || (inMini && targetSrc)) {
    const edgeKey = `${fromKey} -> ${resolvedKey}`
    if (BOUNDARY_ALLOWLIST.has(edgeKey)) return // ngoại lệ có chủ đích (xem comment)
    boundaryViolations.push({
      from: fromKey,
      spec,
      resolvedTo: resolvedKey,
      rule: inMini
        ? 'mini-services → src (mini-service phải độc lập — trừ allowlist có chủ đích ở trên)'
        : 'src → mini-services (app giao tiếp mini-services qua HTTP, không qua import)',
    })
  }
}

for (const file of files) {
  const fromKey = toKey(file)
  if (!graph.has(fromKey)) graph.set(fromKey, new Set())
  const content = fs.readFileSync(file, 'utf8')
  for (const re of STATIC_IMPORT_RE) {
    re.lastIndex = 0
    let m
    while ((m = re.exec(content)) !== null) {
      const resolved = resolveSpec(file, m[1])
      if (!resolved) continue
      recordEdge(file, fromKey, m[1], resolved, true)
    }
  }
  DYNAMIC_IMPORT_RE.lastIndex = 0
  let dm
  while ((dm = DYNAMIC_IMPORT_RE.exec(content)) !== null) {
    const resolved = resolveSpec(file, dm[1])
    if (!resolved) continue
    recordEdge(file, fromKey, dm[1], resolved, false)
  }
}

// ---------------------------------------------------------------------------
// Circular detection — DFS 3 màu; chu trình chuẩn hoá (rotate để node nhỏ nhất
// đứng đầu) để mỗi cycle chỉ báo 1 lần bất kể điểm vào.
// ---------------------------------------------------------------------------
const color = new Map() // 0=white 1=gray 2=black
const stack = []
const foundCycles = new Map() // canonicalKey -> [nodes...] (1 chu trình/điểm vào sâu nhất)

function canonicalCycle(nodes) {
  // nodes: [a, b, c] nghĩa là a→b→c→a
  let minIdx = 0
  for (let i = 1; i < nodes.length; i++) {
    if (nodes[i] < nodes[minIdx]) minIdx = i
  }
  return nodes.slice(minIdx).concat(nodes.slice(0, minIdx))
}

function dfs(node) {
  color.set(node, 1)
  stack.push(node)
  for (const next of graph.get(node) || []) {
    const c = color.get(next) ?? 0
    if (c === 1) {
      // tìm thấy cycle: cắt stack từ vị trí next
      const idx = stack.indexOf(next)
      const cyc = stack.slice(idx)
      const canon = canonicalCycle(cyc)
      foundCycles.set(canon.join(' -> '), canon)
    } else if (c === 0) {
      dfs(next)
    }
  }
  stack.pop()
  color.set(node, 2)
}

for (const key of graph.keys()) {
  if ((color.get(key) ?? 0) === 0) dfs(key)
}

// ---------------------------------------------------------------------------
// Báo cáo
// ---------------------------------------------------------------------------
let fail = false

console.log(`\n[TMO CHECK-IMPORTS] Quét ${files.length} file (${graph.size} module nội bộ)...`)

if (boundaryViolations.length > 0) {
  fail = true
  console.error(`\n✘ IMPORT BOUNDARY VIOLATIONS: ${boundaryViolations.length}`)
  for (const v of boundaryViolations) {
    console.error(`  • ${v.from}`)
    console.error(`      import '${v.spec}' → ${v.resolvedTo}`)
    console.error(`      Rule: ${v.rule}`)
  }
} else {
  console.log('✔ Import boundary sạch (src ↔ mini-services không import chéo).')
}

const newCycles = []
const knownSeen = []
for (const [key, nodes] of foundCycles) {
  if (KNOWN_CYCLES.includes(key)) knownSeen.push(nodes)
  else newCycles.push(nodes)
}

if (newCycles.length > 0) {
  fail = true
  console.error(`\n✘ CIRCULAR IMPORTS MỚI (chưa có trong baseline): ${newCycles.length}`)
  for (const nodes of newCycles) {
    console.error(`  • ${nodes.join(' -> ')} -> ${nodes[0]}`)
  }
  console.error('  Xử lý: tách types ra module 0-import, hoặc đổi 1 chiều sang dynamic import()')
  console.error('  (pattern codebase hiện dùng — xem comment "avoid circular dependency").')
} else {
  console.log(`✔ Không có circular import tĩnh mới${foundCycles.size > 0 ? ` (${foundCycles.size} cycle baseline đã biết)` : ''}.`)
}

if (knownSeen.length > 0) {
  console.warn(`\n⚠ BASELINE cycles (${knownSeen.length}) — đã biết, chỉ cảnh báo:`)
  for (const nodes of knownSeen) {
    console.warn(`  • ${nodes.join(' -> ')} -> ${nodes[0]}`)
  }
  if (!verbose) console.warn('  (chạy với --verbose để xem chi tiết; FAIL chỉ áp dụng cho cycle MỚI)')
}

if (fail) {
  console.error('\n[TMO CHECK-IMPORTS] ✘ FAIL — xem vi phạm ở trên.')
  process.exit(1)
}
console.log('\n[TMO CHECK-IMPORTS] ✔ PASS')
process.exit(0)
